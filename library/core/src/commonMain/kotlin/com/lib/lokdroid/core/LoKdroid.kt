package com.lib.lokdroid.core

import com.lib.lokdroid.data.default_implementation.MultipleLineMessageBuilder
import com.lib.lokdroid.data.default_implementation.TagProvider
import com.lib.lokdroid.data.default_implementation.logger.ConsoleLogger
import com.lib.lokdroid.domain.IFormatter
import com.lib.lokdroid.domain.ILogger
import com.lib.lokdroid.domain.IMessageBuilder
import com.lib.lokdroid.domain.model.Level

/**
 * A singleton logger object responsible for initializing and managing a [LogManager].
 * It provides a centralized logging utility that can be configured and accessed globally
 * throughout an application.
 *
 * The logger starts with a default configuration and can be overridden at any time using [initialize].
 */
object LoKdroid {

    private var logManager: LogManager = LogManager(
        minLevel = Level.Verbose,
        logger = ConsoleLogger,
        formatter = IFormatter { message -> message },
        tagProvider = { TagProvider.getTag() },
        multipleLineMessageBuilderFactory = { MultipleLineMessageBuilder() }
    )

    /**
     * Gets the minimum logging level set for the current [LogManager].
     */
    internal val minLevel: Level
        get() = logManager.minLevel

    /**
     * Initializes the [LoKdroid] with a custom configuration, replacing the current [LogManager].
     * Calling this function is optional because [LoKdroid] starts with an equivalent default configuration.
     *
     * @param minLevel The minimum level of log messages to be processed.
     * @param logger The logger implementation to use for logging messages.
     * @param formatter The formatter used to format log messages.
     * @param tagProvider A lambda function that dynamically provides the tag associated with logs
     * generated by this logger. The tag is evaluated each time a log is generated, allowing it to be dynamic.
     * @param multipleLineMessageBuilderFactory A factory that creates a new [IMessageBuilder] for each
     * multi-line message built through the DSL.
     */
    fun initialize(
        minLevel: Level = Level.Verbose,
        logger: ILogger = ConsoleLogger,
        formatter: IFormatter = IFormatter { message -> message },
        tagProvider: () -> String = { TagProvider.getTag() },
        multipleLineMessageBuilderFactory: () -> IMessageBuilder = { MultipleLineMessageBuilder() }
    ) {
        logManager = LogManager(
            minLevel = minLevel,
            logger = logger,
            formatter = formatter,
            tagProvider = tagProvider,
            multipleLineMessageBuilderFactory = multipleLineMessageBuilderFactory,
        )
    }

    /**
     * Logs a message at the specified level using the configured [LogManager].
     * The message is formatted and logged if the specified level is above or equal to the minimum level.
     *
     * @param level The severity level of the log.
     * @param message The message to log.
     */
    internal fun log(level: Level, message: String) {
        logManager.log(level = level, message = message)
    }

    /**
     * Logs a message constructed using the specified [IMessageBuilder] lambda at the designated level.
     * This allows for more complex message construction.
     *
     * @param level The severity level of the log.
     * @param block A lambda block to configure the [IMessageBuilder].
     */
    internal fun log(level: Level, block: IMessageBuilder.() -> Unit) {
        logManager.log(level = level, block = block)
    }
}
